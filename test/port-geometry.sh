#!/bin/sh
# Regenerates core/geometry.js from the prototype's hyper.js. Mechanical: drop the UMD wrapper, export the api.
set -eu
H=${1:-/workspace/hyperbolic-workspaces/hyper.js}
OUT=$(dirname "$0")/../core/geometry.js
n=$(wc -l < "$H")
{ echo "// Mechanical ESM port of prototype hyper.js. Generated by test/port-geometry.sh: the UMD wrapper"
  echo "// (hyper.js:5, :709-713) becomes one export line. Do not edit by hand."
  sed -n '1,4p' "$H"; sed -n "6,$((n-5))p" "$H"; echo
  sed -n 's/^const api = {\(.*\)}$/export {\1}/p' "$H"; } > "$OUT"
